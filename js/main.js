  function citation(b, full) {
    if (!b) return "";
    let authors = b.authors || "";
    if (!full && authors.length > 90) authors = authors.slice(0, 88).replace(/,[^,]*$/, "") + ", et al.";
    const links = [b.doi && `<a href="https://doi.org/${esc(b.doi)}" rel="noopener">DOI</a>`,
                   b.pmid && `<a href="https://pubmed.ncbi.nlm.nih.gov/${esc(b.pmid)}/" rel="noopener">PubMed</a>`]
      .filter(Boolean).join(" · ");
    const where = [b.journal, b.volume && `${b.volume}${b.issue ? `(${esc(b.issue)})` : ""}`, b.pages].filter(Boolean).map(esc).join(" ");
    return `<p class="mp-cite">${esc(authors)}${b.year ? ` (${esc(b.year)})` : ""}. <span class="t">${b.title || ""}</span>
      ${where ? `<i>${where}</i>.` : ""} ${links}</p>`;
  }

  function flagsBlock(e) {
    if (!e.flags) return "";
    const isErr = e.issues === "error";
    const items = e.flags.map((f) => `<li>${f[0] === "e" ? "Error" : "Warning"}: ${esc(f[2])}</li>`).join("");
    return `<details class="mp-flags${isErr ? " error" : ""}"><summary>${e.flags.length} data
      ${e.flags.length === 1 ? "issue" : "issues"} for curators</summary><ul>${items}</ul></details>`;
  }

  function relatedChips(e) {
    if (!e.rel || !e.rel.length) return "";
    const chips = e.rel.map((id) => {
      const x = state.data.relPdb[id.toUpperCase()];
      const tip = x ? `From PDB: ${x.method || ""}${x.res ? `, ${fmtRes(x.res)}` : ""}. ${x.title || ""}` : "Not found in the PDB";
      const fresh = state.newRel.get(id.toUpperCase());
      return `<a class="mp-chip${fresh ? " new" : ""}" href="#/pdb/${esc(id.toUpperCase())}" title="${esc(fresh ? `New · added ${fmtDate(fresh.at)} by ${fresh.byName || fresh.by}. ${tip}` : tip)}">${esc(id)}${fresh ? '<span class="mp-visually-hidden"> (new)</span>' : ""}</a>`;
    }).join("");
    return `<div class="mp-chips"><span class="mp-badge related">Related</span>${chips}</div>`;
  }

  function resolutionCell(e) {
    const curated = e.res ? esc(e.res.match(/^[\d.]+$/) ? `${e.res} Å` : e.res) : "—";
    const x = e.x;
    const fromPdb = x ? ` <span class="mp-frompdb">(from PDB: ${esc(x.method || "")}${x.res ? `, ${fmtRes(x.res)}` : ""})</span>` : "";
    return curated + fromPdb;
  }

  function entryCard(e, opts = {}) {
    const isD = e.kind === "d";
    const body = `
      <div class="mp-entry-head">
        <span class="mp-badge${isD ? " daughter" : ""}">${isD ? "Daughter" : "Parent"}</span>
        ${newBadge(e)}
        <a class="mp-pdb" href="#/entry/${e.k}">${esc(e.pdb)}</a>
        <a href="${rcsb(e.pdb)}" rel="noopener" class="mp-of">RCSB ↗</a>
        ${isD && opts.showParent ? `<span class="mp-of">daughter of <a href="#/entry/${e.parent.k}">${esc(e.parent.pdb)}</a></span>` : ""}
        <h3>${e.name || esc(e.pdb)}</h3>
      </div>
      <dl class="mp-meta">
        <dt>Species</dt><dd>${e.species || "—"}${e.domain ? ` <span class="mp-frompdb">(${esc(e.domain)})</span>` : ""}</dd>
        <dt>Expressed in</dt><dd>${e.host ? esc(e.host) : "Not stated"}</dd>
        <dt>Resolution</dt><dd>${resolutionCell(e)}</dd>
      </dl>
      ${e.desc ? `<div class="mp-desc">${e.desc}</div>` : ""}
      ${citation((e.bib || [])[0], false)}
      ${relatedChips(e)}
      ${flagsBlock(e)}`;
    let daughters = "";
    if (!isD && e.d && e.d.length && !opts.noDaughters) {
      const ds = opts.filter ? e.d.filter(opts.filter) : e.d;
      if (ds.length) {
        // Every structure under a parent counts as a daughter structure, related entries included.
        const nRel = (e.rel || []).length + e.d.reduce((n, d) => n + (d.rel || []).length, 0);
        const total = e.d.length + nRel;
        const label = ds.length === e.d.length
          ? `${total} daughter ${total === 1 ? "structure" : "structures"} of ${esc(e.pdb)}${nRel ? ` (${e.d.length} described in full, ${nRel} related)` : ""}`
          : `${ds.length} of the ${e.d.length} fully described daughter structures of ${esc(e.pdb)} match the filters`;
        daughters = `<details class="mp-daughters"${ds.length <= 4 || opts.openDaughters ? " open" : ""}>
          <summary>${label}</summary>${ds.map((d) => entryCard(d)).join("")}</details>`;
      }
    }
    const pic = opts.noThumb ? "" : thumb(e.pdb);
    return `<article class="mp-entry${isD ? " daughter" : ""}${pic ? " has-thumb" : ""}" id="e-${e.k}">${pic}${body}${daughters}</article>`;
  }

